#!/usr/bin/env python3
"""Rewrite Sources/Search/Fork/BangList.swift from DuckDuckGo's bang list.

Keeps the COUNT most used bangs (DuckDuckGo's own `r` rank). Every other
!bang still works: Copper hands it to DuckDuckGo on Return.

    python3 tools/bangs/refresh.py [COUNT]   # default 200
"""
import json, re, sys, urllib.request
from pathlib import Path

COUNT = int(sys.argv[1]) if len(sys.argv) > 1 else 200
OUT = Path(__file__).resolve().parents[2] / "Sources/Search/Fork/BangList.swift"

data = json.load(urllib.request.urlopen("https://duckduckgo.com/bang.js", timeout=60))
data.sort(key=lambda b: -b.get("r", 0))

def usable(template):
    # http(s), the words once, and never in the host (a bang must stay on its site).
    m = re.match(r"^https?://([^/?#]+)", template)
    return m and template.count("{{{s}}}") == 1 and "{{{s}}}" not in m.group(1) and "%s" not in template

def swift(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

rows, seen = [], set()
for bang in data:
    trigger, template = bang["t"].lower(), bang["u"].strip()
    if trigger in seen or not usable(template) or not re.fullmatch(r"[a-z0-9._-]+", trigger):
        continue
    seen.add(trigger)
    rows.append(f"        ({swift(trigger)}, {swift(bang['s'].strip())}, {swift(template.replace('{{{s}}}', '%s'))}),")
    if len(rows) == COUNT:
        break

OUT.write_text(
    "// Generated by tools/bangs/refresh.py from https://duckduckgo.com/bang.js — do not edit.\n"
    f"// The {len(rows)} most used !bangs: trigger, site, address (%s = the words).\n\n"
    "extension Bangs {\n"
    "    static let bundled: [(String, String, String)] = [\n"
    + "\n".join(rows) + "\n    ]\n}\n"
)
print(f"{len(rows)} bangs → {OUT}")
