import Foundation

// copper.d.ts, written from the tool registry's own JSON schemas, so what a
// copper_run script may call is typed by the same words the tools are
// described with — and never drifts from them. Copper does not type-check
// anything: an agent that wants to runs tsgo or tsrs over this file and its
// script before sending it (docs/agents.md › Code mode). The app carries no
// compiler.

@MainActor
enum CodeModeTypes {
    /// The `copper` object's shape in one line, for copper_run's description:
    /// "copper.browser.{tabs, navigate, …}; copper.canvas.{…}".
    static func summary(_ names: [String]) -> String {
        var order: [String] = []
        var byNamespace: [String: [String]] = [:]
        for name in names {
            let (namespace, method) = split(name)
            if byNamespace[namespace] == nil { order.append(namespace) }
            byNamespace[namespace, default: []].append(method)
        }
        return order.map { "copper.\($0).{\(byNamespace[$0]?.joined(separator: ", ") ?? "")}" }.joined(separator: "; ")
    }

    /// `browser_navigate_back` → (`browser`, `navigateBack`). Matches the
    /// shim in CodeMode.swift, which builds the object the same way.
    static func split(_ name: String) -> (namespace: String, method: String) {
        guard let underscore = name.firstIndex(of: "_") else { return ("copper", camel(name)) }
        return (String(name[..<underscore]), camel(String(name[name.index(after: underscore)...])))
    }

    private static func camel(_ snake: String) -> String {
        var out = ""
        var up = false
        for character in snake {
            if character == "_" { up = true; continue }
            out.append(up ? Character(character.uppercased()) : character)
            up = false
        }
        return out
    }

    // MARK: - the declaration file

    static func declarations(_ tools: [[String: Any]]) -> String {
        var order: [String] = []
        var byNamespace: [String: [[String: Any]]] = [:]
        for tool in tools {
            guard let name = tool["name"] as? String else { continue }
            let namespace = split(name).namespace
            if byNamespace[namespace] == nil { order.append(namespace) }
            byNamespace[namespace, default: []].append(tool)
        }
        var out = """
        // copper.d.ts — the `copper` object a copper_run script sees, generated by Copper \(Fork.version)
        // from its tool registry. Plain JavaScript runs; these declarations are for checking a
        // script before sending it (docs/agents.md › Code mode). Regenerate with the copper_types tool.

        /** What every tool call resolves to. */
        interface CopperResult {
          /** The tool's text answer (every text part, joined). */
          text: string;
          /** `text` parsed, when the tool answered JSON. */
          json?: unknown;
          /** Pictures the tool returned (screenshots), base64. */
          images?: { mimeType: string; data: string }[];
          /** The tool's one-line summary of what it did, when it left one. */
          summary?: string;
        }

        /** A call that failed rejects with one of these; `tool` is the tool's name. */
        interface CopperToolError extends Error {
          name: "CopperToolError";
          tool: string;
        }


        """
        var members: [String] = []
        for namespace in order {
            let typeName = "Copper" + namespace.prefix(1).uppercased() + namespace.dropFirst()
            out += "interface \(typeName) {\n"
            for tool in byNamespace[namespace] ?? [] {
                guard let name = tool["name"] as? String else { continue }
                let method = split(name).method
                out += doc(tool["description"] as? String ?? "", indent: "  ")
                out += "  \(method)(\(parameter(tool["inputSchema"] as? [String: Any], indent: "  "))): Promise<CopperResult>;\n"
            }
            out += "}\n\n"
            members.append("  \(namespace): \(typeName);")
        }
        out += "interface Copper {\n"
        out += members.joined(separator: "\n") + (members.isEmpty ? "" : "\n")
        out += """
          /** Any tool by its MCP name (`\"browser_snapshot\"`), for a name built at run time. */
          call(tool: string, args?: Record<string, unknown>): Promise<CopperResult>;
          /** Wait, at most 30 s and never past the run's timeout. */
          sleep(ms: number): Promise<void>;
          /** The MCP names of the tools this object has. */
          readonly tools: readonly string[];
        }

        declare const copper: Copper;

        /** Lines come back in the answer's `logs` (200 lines, 64 KB). */
        declare const console: {
          log(...parts: unknown[]): void;
          info(...parts: unknown[]): void;
          warn(...parts: unknown[]): void;
          error(...parts: unknown[]): void;
          debug(...parts: unknown[]): void;
        };

        """
        return out
    }

    /// The `args` parameter: optional when the schema requires nothing.
    private static func parameter(_ schema: [String: Any]?, indent: String) -> String {
        let required = (schema?["required"] as? [String]) ?? []
        let properties = (schema?["properties"] as? [String: Any]) ?? [:]
        if properties.isEmpty { return "args?: Record<string, never>" }
        return "args\(required.isEmpty ? "?" : ""): \(object(properties, required: required, indent: indent))"
    }

    private static func object(_ properties: [String: Any], required: [String], indent: String) -> String {
        var out = "{\n"
        for key in properties.keys.sorted(by: { a, b in
            // Required first, then the rest, each alphabetically.
            let ra = required.contains(a), rb = required.contains(b)
            return ra != rb ? ra : a < b
        }) {
            let property = properties[key] as? [String: Any] ?? [:]
            out += doc(property["description"] as? String ?? "", indent: indent + "  ")
            out += "\(indent)  \(identifier(key))\(required.contains(key) ? "" : "?"): \(type(property, indent: indent + "  "));\n"
        }
        out += "\(indent)}"
        return out
    }

    /// A JSON schema as a TypeScript type.
    static func type(_ schema: [String: Any], indent: String) -> String {
        if let values = schema["enum"] as? [Any] {
            return values.map { value -> String in
                if let text = value as? String { return quote(text) }
                return "\(value)"
            }.joined(separator: " | ")
        }
        if let options = (schema["oneOf"] ?? schema["anyOf"]) as? [[String: Any]] {
            return options.map { type($0, indent: indent) }.joined(separator: " | ")
        }
        switch schema["type"] as? String {
        case "string": return "string"
        case "number", "integer": return "number"
        case "boolean": return "boolean"
        case "null": return "null"
        case "array":
            let items = schema["items"] as? [String: Any] ?? [:]
            let inner = type(items, indent: indent)
            return inner.contains(" | ") || inner.hasPrefix("{") ? "(\(inner))[]" : "\(inner)[]"
        case "object":
            if let properties = schema["properties"] as? [String: Any], !properties.isEmpty {
                return object(properties, required: (schema["required"] as? [String]) ?? [], indent: indent)
            }
            if let extra = schema["additionalProperties"] as? [String: Any] { return "Record<string, \(type(extra, indent: indent))>" }
            return "Record<string, unknown>"
        default:
            return "unknown"
        }
    }

    /// A `/** … */` block, wrapped at about a hundred columns.
    private static func doc(_ text: String, indent: String) -> String {
        let clean = text.replacingOccurrences(of: "*/", with: "*\u{200B}/").trimmingCharacters(in: .whitespacesAndNewlines)
        guard !clean.isEmpty else { return "" }
        var lines: [String] = []
        var line = ""
        for word in clean.split(separator: " ", omittingEmptySubsequences: true) {
            if !line.isEmpty, line.count + word.count + 1 > 100 - indent.count - 4 {
                lines.append(line)
                line = ""
            }
            line += (line.isEmpty ? "" : " ") + word
        }
        if !line.isEmpty { lines.append(line) }
        if lines.count == 1 { return "\(indent)/** \(lines[0]) */\n" }
        return "\(indent)/**\n" + lines.map { "\(indent) * \($0)\n" }.joined() + "\(indent) */\n"
    }

    private static func identifier(_ key: String) -> String {
        let plain = key.allSatisfy { $0.isLetter || $0.isNumber || $0 == "_" || $0 == "$" } && !(key.first?.isNumber ?? true)
        return plain ? key : quote(key)
    }

    private static func quote(_ text: String) -> String {
        "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}
